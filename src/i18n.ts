const dicts: Record<Lang, Record<Key, string>> = { ja, en };
let lang: Lang = "ja";

export function currentLang(): Lang {
  return lang;
}

export function t(key: Key): string {
  return dicts[lang][key] ?? ja[key];
}

/** data-i18n（テキスト）/ data-i18n-html（信頼できる辞書の HTML）/ data-i18n-title を置き換える */
export function applyI18n(root: ParentNode = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n as Key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml as Key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle as Key);
  });
}

/** Rust 側で決めた言語を読み込み、変更を購読する */
export async function initI18n(onChange?: () => void) {
  lang = (await invoke<Lang>("get_language")) === "en" ? "en" : "ja";
  applyI18n();
  await listen<Lang>("language-changed", (e) => {
    lang = e.payload === "en" ? "en" : "ja";
    applyI18n();
    onChange?.();
  });
}
